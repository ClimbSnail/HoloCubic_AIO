/*
Function: QQ Super Emojis
Operation Instructions: Left/Right to select different emojis, Tilt down to play current emoji, Tilt back to exit current playback/exit current function
Other:
QQ Super Emojis are lottie animations, it's difficult for microcontrollers to parse lottie animations directly (but can be implemented)
For how to get QQ Super Emojis, see:
[Transparent Mini TV & QQ Super Emojis] https://www.bilibili.com/video/BV1dC4y1q7R7/?share_source=copy_web&vd_source=68337adbea96c8cef50403a4b2809df6

The emoji function depends on the video playback library in the media_player APP

SD card storage instructions (emoji related functions):
./LH&LXW/emoji/videos/videox.mjpeg Store videos to play (size 240x240) (x is 0~99)
./LH&LXW/emoji/images/imagex.bin   Store cover images for the videos (size 60x60) (x is 0~99)
./LH&LXW/emoji/emoji_num.txt       Store number of videos to play (00~99), e.g., for 7 videos, write 07

The number of videos in ./LH&LXW/emoji/videos/ must equal the number of covers in ./LH&LXW/emoji/images/
and must equal the number of videos entered by user in ./LH&LXW/emoji/emoji_num.txt

Covers must be generated by the img tool from the official LVGL website, multi-function PC software cannot generate them

So when using this function as a video player, steps to add custom videos are:
1. Get the video, use multi-function PC software to convert to 240x240 mjpeg format (recommended to use default parameters)
2. Rename this video to videoxx.mjpeg
3. Extract an image from this video, aspect ratio preferably 1:1
4. Rename this image to imagexx.jpg
5. Use Windows built-in Paint to resize it to 60x60 (no need to maintain original aspect ratio when resizing)
6. Use LVGL official website's img tool to convert it to imagexx.bin
7. Put imagexx.bin and videoxx.mjpeg in corresponding SD card folder
8. Modify the total number of videos in emoji_num.txt
9. Open APP, and you can see the corresponding video in emoji function
(If you want black video background, you can use editing software; or use openCV, but it only supports solid color backgrounds;
OpenCV batch replace all QQ Super Emoji background colors:
[QQ Super Emoji Background Color Replacement] https://www.bilibili.com/video/BV1cb4y1G7Sy/?share_source=copy_web&vd_source=68337adbea96c8cef50403a4b2809df6)
*/

/* System variables */
extern bool isCheckAction;
extern ImuAction *act_info;

#define emoji_play_time 33333  // One emoji plays (emoji_play_time)ms then automatically plays next, can also switch manually

EMOJI_RUN *emj_run = NULL;

static void emoji_init(void){
    emj_run = (EMOJI_RUN*)calloc(1,sizeof(EMOJI_RUN));  // If using malloc here, video playback will fail!!!
    if(emj_run == NULL){
        Serial.println("1:lack of memory");
        while(1);
    }
    emj_run->emoji_var = 1;  // Reset currently selected emoji number
    emj_run->mpu6050key_var = 0;  // After entering APP, mpu6050 status value, left tilt is 2, right tilt is 1, others are 0
    emj_run->emoji_mode = true;  // App running mode, true for selecting emoji, false for emoji playback
    File dataFile = SD.open("/LH&LXW/emoji/emoji_num.txt","r");  // Create File object to read from SPIFFS
    emj_run->emoji_Maxnum = (dataFile.read() - '0')*10;
    emj_run->emoji_Maxnum += (dataFile.read() - '0');  // Total number of emojis (don't know how to use SPIFFS, so manually input count, i.e., read SD card config file)
    Serial.print(emj_run->emoji_Maxnum);
    dataFile.close();  // After reading is complete, close the file
    EMOJI_GUI_Init();
}

/* Close player */
static void close_player(void){
    delete emj_run->emoji_docoder;
    emj_run->emoji_file.close();
}
/* Start player */
static void start_player(void){
    char *path = (char*)malloc(38);  // Must use char* type, cannot use uint8_t*
    sprintf(path,"/LH&LXW/emoji/videos/video%d.mjpeg",emj_run->emoji_var);  // Icon path
    emj_run->emoji_file = tf.open(path);
    emj_run->emoji_docoder = new MjpegPlayDocoder(&emj_run->emoji_file, true);
    free(path);
}
void emoji_process(lv_obj_t *ym)
{
    unsigned long *timCont = (unsigned long*)malloc(4);
    emoji_init();
    act_info->active = ACTIVE_TYPE::UNKNOWN;
    act_info->isValid = 0;
    while(1){
        /* Refresh LVGL only when selecting emojis */
        if(emj_run->emoji_mode)lv_timer_handler();
        else{
            if(emj_run->emoji_file.available()){
                emj_run->emoji_docoder->video_play_screen();  // Play one frame of data
            }else{
                /* Check if more than 3333ms has passed */
                if(millis()-(*timCont) > emoji_play_time){
                    next_emoji();  // Update selected emoji on emoji selection page
                    emj_run->emoji_var ++;
                    if(emj_run->emoji_var > emj_run->emoji_Maxnum)emj_run->emoji_var = 1;
                    *timCont = millis();
                }
                close_player();
                start_player();
                emj_run->emoji_docoder->video_play_screen();  // Immediately play one frame of data
            }
        }
        /* MPU6050 data acquisition */
        if (isCheckAction){
            isCheckAction = false;
            act_info = mpu.getAction();
        }

        /* MPU6050 action response */
        if (RETURN == act_info->active){
            /* When selecting emoji, tilt back to exit app */
            if(emj_run->emoji_mode){
                EMOJI_GUI_DeInit(ym);  // There's LVGL animation when exiting APP, so must wait for animation to end before calling system exit function, so UI exit cannot be placed in LHLXW_exit_callback
                lv_obj_invalidate(lv_scr_act());  // Even if cache hasn't changed, let LVGL update entire screen next time
                /* Delay 999ms to prevent exiting app simultaneously */
                for(uint16_t i=0;i<898;i++){
                    lv_timer_handler();  // Let LVGL update screen so operator can see executed action
                    delay(1);
                }
                // close_player();  // Player must be closed here, calling system will definitely crash otherwise
                free(emj_run);  // Release memory
                return;  // Exit this function
            }
            /* When playing emoji, tilt back to exit emoji playback */
            else{
                emj_run->emoji_mode = true;
                close_player();  // Close playback
                lv_obj_invalidate(lv_scr_act());  // Even if cache hasn't changed, let LVGL update entire screen next time
                /* Delay 999ms to prevent exiting emoji function simultaneously */
                for(uint16_t i=0;i<898;i++){
                    lv_timer_handler();  // Let LVGL update screen so operator can see executed action
                    delay(1);
                }
            }
        }else if(TURN_RIGHT == act_info->active && emj_run->mpu6050key_var != 1){
            if(emj_run->emoji_mode)
                emj_run->mpu6050key_var = 1;
            else{
                next_emoji();  // Update selected emoji on emoji selection page
                emj_run->emoji_var ++;
                if(emj_run->emoji_var > emj_run->emoji_Maxnum)emj_run->emoji_var = 1;
                *timCont = millis();  // Restart timer
                close_player();
                start_player();
            }
            for(uint16_t i=0;i<388;i++){
                if(emj_run->emoji_mode)lv_timer_handler();
                delay(1);
            }
        }else if(TURN_LEFT == act_info->active && emj_run->mpu6050key_var != 2){
            if(emj_run->emoji_mode)
                emj_run->mpu6050key_var = 2;
            else{
                prev_emoji();  // Update selected emoji on emoji selection page
                emj_run->emoji_var --;
                if(emj_run->emoji_var < 1)emj_run->emoji_var = emj_run->emoji_Maxnum;
                *timCont = millis();  // Restart timer
                close_player();
                start_player();
            }
            for(uint16_t i=0;i<388;i++){
                if(emj_run->emoji_mode)lv_timer_handler();
                delay(1);
            }
        }else if(act_info->active == UP){
            if(emj_run->emoji_mode){
                start_player();
                emj_run->emoji_mode = false;
                *timCont = millis();  // Record playback start time
            }
        }
        act_info->active = ACTIVE_TYPE::UNKNOWN;
        act_info->isValid = 0;
    }
    free(timCont);
}
